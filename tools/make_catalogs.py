# Langue de référence : l'anglais (langue par défaut de l'app). Le français est
# proposé dans les réglages de l'app. Les clés restent les textes français du
# code ; le français est donc écrit explicitement pour chaque clé.
SOURCE = "en"

def catalog(entries):
    strings = {}
    for key in sorted(entries):
        strings[key] = {"localizations": {
            "en": {"stringUnit": {"state": "translated", "value": entries[key]}},
            "fr": {"stringUnit": {"state": "translated", "value": key}}}}
    return {"sourceLanguage": SOURCE, "strings": strings, "version": "1.0"}

def write(path, data):
    with open(path, "w", encoding="utf-8") as f:
        # Même mise en forme qu'Xcode (« clé : valeur ») : il n'a plus de raison
        # de réécrire ces fichiers, ce qui évite des conflits lors des mises à jour.
        json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True, separators=(",", " : "))
        f.write("\n")

root = sys.argv[1]
problems = []
for folder in ("ScooterPower", "ScooterPowerWidgets"):
    used = keys(root + "/" + folder)
    missing = sorted(k for k in used if k not in EN)
    if missing:
        problems.append((folder, missing))
    entries = {k: EN[k] for k in used if k in EN}
    for key, value in entries.items():
        assert key.count("%@") == value.count("%@"), ("nombre de paramètres", key)
    write(f"{root}/{folder}/Localizable.xcstrings", catalog(entries))
    print(folder, len(entries), "textes traduits")

